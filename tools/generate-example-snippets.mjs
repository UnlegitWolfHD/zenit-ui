#!/usr/bin/env node
/*
 * Copies the real sources of the example application into one TypeScript file,
 * so that the page "Einbindung" and the code disclosures of the Gameserver page
 * can only ever show code that exists.
 *
 * Why a generator and not an import of the files as text: the application
 * builder would apply esbuild's text loader, but the TypeScript compiler runs
 * first and resolves `import quelle from './gameserver.ts' with { loader:
 * 'text' }` as a module. It then fails with TS1192 ("has no default export")
 * and TS5097 ("An import path can only end with a '.ts' extension when
 * 'allowImportingTsExtensions' is enabled"). That is checked, not assumed. For
 * non-TypeScript files an import attribute plus an ambient module declaration
 * would work, but then the example would carry two mechanisms; this one covers
 * every file type.
 *
 * Regions are not cut here. The generated file holds whole files, and the
 * application picks the marked regions out of them at runtime with
 * `ausschnitt()`, which is a pure function with its own unit test.
 *
 *   node tools/generate-example-snippets.mjs           writes the file
 *   node tools/generate-example-snippets.mjs --check    fails when it is stale
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { argv } from 'node:process';

/** Files shown verbatim. The key is what the caption of the code block shows. */
const DATEIEN = [
  'projects/beispiel-app/src/index.html',
  'projects/beispiel-app/src/styles.css',
  'projects/beispiel-app/src/main.ts',
  'projects/beispiel-app/src/app/app.config.ts',
  'projects/beispiel-app/src/app/app.routes.ts',
  'projects/beispiel-app/src/app/layout/shell/shell.ts',
  'projects/beispiel-app/src/app/layout/theme-control/theme-control.ts',
  'projects/beispiel-app/src/app/pages/gameserver/gameserver.ts',
  'projects/beispiel-app/src/app/gameserver/gameserver-data.ts',
  'projects/beispiel-app/src/app/gameserver/server-list/server-list.ts',
  'projects/beispiel-app/tsconfig.app.json',
];

/** Path of the generated file, relative to the workspace root. */
const ZIEL = 'projects/beispiel-app/src/app/shared/quelltexte.generated.ts';

/** Key of the derived excerpt of angular.json. */
const ANGULAR_AUSZUG = 'angular.json (Auszug)';

/**
 * The styles of the example application as they stand in angular.json. Derived
 * instead of copied: a changed order in angular.json changes the shown excerpt.
 */
function angularAuszug() {
  const angular = JSON.parse(readFileSync('angular.json', 'utf8'));
  const optionen = angular.projects['beispiel-app'].architect.build.options;
  return [
    '"beispiel-app": {',
    '  "architect": {',
    '    "build": {',
    '      "options": {',
    `        "styles": ${JSON.stringify(optionen.styles, null, 2).split('\n').join('\n        ')}`,
    '      }',
    '    }',
    '  }',
    '}',
  ].join('\n');
}

function inhalt() {
  const texte = {};
  for (const datei of DATEIEN) {
    texte[datei] = readFileSync(datei, 'utf8').replace(/\r\n/g, '\n');
  }
  texte[ANGULAR_AUSZUG] = angularAuszug();
  return [
    '/*',
    ' * Generated by tools/generate-example-snippets.mjs. Do not edit.',
    ' *',
    ' * The verbatim text of the files the example application shows. Run',
    ' * `npm run check:snippets` to find out whether it still matches the sources;',
    ' * `npm run build:beispiel` and `npm run start:beispiel` rewrite it.',
    ' */',
    'export const QUELLTEXTE: Readonly<Record<string, string>> = ' +
      JSON.stringify(texte, null, 2) +
      ';',
    '',
  ].join('\n');
}

const neu = inhalt();

if (argv.includes('--check')) {
  let alt = '';
  try {
    alt = readFileSync(ZIEL, 'utf8').replace(/\r\n/g, '\n');
  } catch {
    alt = '';
  }
  if (alt !== neu) {
    console.error(
      `${ZIEL} does not match the sources any more.\n` +
        'Run `node tools/generate-example-snippets.mjs` and commit the result.',
    );
    process.exitCode = 1;
  } else {
    console.log(`${ZIEL} is up to date (${DATEIEN.length + 1} entries).`);
  }
} else {
  writeFileSync(ZIEL, neu);
  console.log(`${ZIEL} written (${DATEIEN.length + 1} entries).`);
}
